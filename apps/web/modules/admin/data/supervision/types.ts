import { z } from "zod";

const uuid = z.string().uuid();

export const supervisionSchema = z.object({
  as_of: z.string(),
  read_only: z.boolean(),
  organizations: z.array(z.object({
    id: uuid,
    display_name: z.string(),
    legal_name: z.string(),
    status: z.string(),
    created_at: z.string(),
    member_count: z.number().int().nonnegative(),
    open_requests: z.number().int().nonnegative(),
    open_disputes: z.number().int().nonnegative(),
  })),
  requests: z.array(z.object({
    id: uuid,
    organization_id: uuid,
    organization_name: z.string(),
    status: z.string(),
    library_id: uuid,
    service_id: uuid,
    created_at: z.string(),
    matching_runs: z.number().int().nonnegative(),
    rfq_count: z.number().int().nonnegative(),
    quote_count: z.number().int().nonnegative(),
  })),
  quotes: z.array(z.object({
    id: uuid,
    rfq_id: uuid,
    request_id: uuid,
    provider_organization_id: uuid,
    provider_name: z.string(),
    client_name: z.string(),
    status: z.string(),
    updated_at: z.string().nullable(),
  })),
  missions: z.array(z.object({
    id: uuid,
    contract_id: uuid,
    status: z.string(),
    client_organization_id: uuid,
    provider_organization_id: uuid,
    client_name: z.string(),
    provider_name: z.string(),
    updated_at: z.string().nullable(),
    milestone_count: z.number().int().nonnegative(),
    deliverable_count: z.number().int().nonnegative(),
  })),
  diagnostics: z.array(z.object({
    id: uuid,
    organization_id: uuid,
    organization_name: z.string(),
    status: z.string(),
    rating: z.string(),
    overall_score: z.union([z.number(), z.string()]),
    completed_at: z.string().nullable(),
  })),
  work_enrichment: z.record(z.string(), z.object({
    organization_name: z.string().nullable(),
    assignee_label: z.string().nullable(),
  })).default({}),
  matching: z.array(z.object({
    id: uuid,
    request_id: uuid,
    organization_id: uuid,
    organization_name: z.string(),
    status: z.string(),
    policy_version: z.string(),
    started_at: z.string().nullable(),
    eligible_count: z.number().int().nonnegative(),
    excluded_count: z.number().int().nonnegative(),
    rfq_count: z.number().int().nonnegative(),
    candidates: z.array(z.object({
      provider_organization_id: uuid,
      provider_name: z.string(),
      eligible: z.boolean(),
      score_basis_points: z.number().int(),
      exclusion_reasons: z.array(z.string()).default([]),
    })).default([]),
  })).default([]),
  contracts: z.array(z.object({
    id: uuid,
    status: z.string(),
    current_version: z.number().int().nonnegative(),
    client_organization_id: uuid,
    provider_organization_id: uuid,
    client_name: z.string(),
    provider_name: z.string(),
    signature_count: z.number().int().nonnegative(),
    mission_id: uuid.nullable(),
  })).default([]),
  amendments: z.array(z.object({
    id: uuid,
    contract_id: uuid,
    status: z.string(),
    amendment_number: z.number().int().nonnegative(),
    price_delta_minor: z.string(),
    client_name: z.string(),
    provider_name: z.string(),
    client_organization_id: uuid,
  })).default([]),
  documents: z.array(z.object({
    id: uuid,
    kind: z.string(),
    code: z.string(),
    status: z.string(),
    organization_id: uuid,
    organization_name: z.string(),
    expires_on: z.string().nullable(),
    version: z.number().int().nonnegative(),
  })).default([]),
  messages: z.array(z.object({
    id: uuid,
    subject: z.string(),
    status: z.string(),
    object_id: uuid,
    service_request_id: uuid,
    client_organization_id: uuid,
    provider_organization_id: uuid,
    client_name: z.string(),
    provider_name: z.string(),
    created_at: z.string(),
  })).default([]),
  exceptions: z.array(z.object({
    id: uuid,
    source_kind: z.string(),
    priority: z.string(),
    status: z.string(),
    due_at: z.string(),
    title_fr: z.string(),
    title_ar: z.string(),
    resource_type: z.string(),
    resource_id: z.string(),
    organization_id: uuid.nullable(),
  })).default([]),
  templates: z.array(z.object({
    id: uuid,
    template_code: z.string(),
    event_type: z.string(),
    category_code: z.string(),
    locale: z.string(),
    version: z.number().int().positive(),
    status: z.string(),
    mandatory: z.boolean(),
    channels: z.array(z.string()).default([]),
  })).default([]),
}).passthrough();

export const ficheSchema = z.object({
  organization: z.object({
    id: uuid,
    display_name: z.string(),
    legal_name: z.string(),
    status: z.string(),
    country_code: z.string(),
    created_at: z.string(),
    updated_at: z.string().nullable(),
  }),
  memberships: z.array(z.object({
    id: uuid,
    user_id: uuid,
    status: z.string(),
    roles: z.array(z.string()),
  })),
  requests: z.array(z.object({ id: uuid, status: z.string(), created_at: z.string(), service_id: uuid })),
  missions: z.array(z.object({
    id: uuid, status: z.string(), updated_at: z.string().nullable(), as_client: z.boolean(), as_provider: z.boolean(),
  })),
  disputes: z.array(z.object({
    id: uuid, status: z.string(), urgency: z.string(), mission_id: uuid, response_due_at: z.string(),
  })),
  diagnostics: z.array(z.object({
    id: uuid, status: z.string(), rating: z.string(), overall_score: z.union([z.number(), z.string()]), completed_at: z.string().nullable(),
  })),
  subscriptions: z.array(z.object({
    id: uuid, status: z.string(), plan_version_id: uuid.nullable(), current_period_end: z.string().nullable(),
  })),
  timeline: z.array(z.object({
    at: z.string().nullable(), kind: z.string(), label: z.string(), ref: z.string(),
  })),
}).passthrough();

export type AdminSupervisionDashboard = z.infer<typeof supervisionSchema>;
export type AdminOrganizationFiche = z.infer<typeof ficheSchema>;
export type AdminSupervisionResult<T> =
  | { status: "success"; value: T }
  | { status: "error"; reason: "UNAUTHENTICATED" | "FORBIDDEN" | "UNAVAILABLE" | "INVALID_RESPONSE" | "NOT_FOUND" };
