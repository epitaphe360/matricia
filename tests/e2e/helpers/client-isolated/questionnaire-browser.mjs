import { requireDevelopment, loadOwnState } from './safety.mjs';
requireDevelopment();
const actorLabel=process.argv.find(argument=>argument.startsWith('--actor='))?.slice(8)??'owner';
if(!/^[a-z][a-z0-9-]{1,32}$/u.test(actorLabel))throw new Error('INVALID_TEST_ACTOR_LABEL');
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import {execFileSync}from 'node:child_process';
const require = createRequire(resolve('apps/web/package.json')), { createServerClient } = require('@supabase/ssr'), { chromium, expect } = createRequire(resolve('package.json'))('@playwright/test');
const s = await loadOwnState(), owner = JSON.parse(await readFile(resolve(s.directory, 'actors.private.json'))).find(a => a.label === actorLabel);
const fixture = JSON.parse(await readFile(resolve(s.directory, 'questionnaire-fixture-provenance.json')));
const api = `http://127.0.0.1:${s.gatewayPort}`, origin = `http://127.0.0.1:${s.appPort}`, bag = new Map(), ssr = createServerClient(api, s.anonKey, { cookies: { getAll: () => [...bag.values()], setAll: items => items.forEach(item => bag.set(item.name, item)) } });
if ((await ssr.auth.setSession(owner.session)).error)
    throw new Error('NATIVE_SSR_SESSION_FAILED');
const dir = resolve(s.directory, 'questionnaire-browser');
await mkdir(dir, { recursive: true });
const proof = { scope: 'NATIVE_CLIENT_CONDITIONAL_QUESTIONNAIRE',appTree:execFileSync('git',['rev-parse','HEAD:apps/web'],{encoding:'utf8'}).trim(), candidate:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),sourceArchiveSha256:s.baselineArchiveSha256,additionalMigrations:s.additionalMigrations??[], status: 'RUNNING', nativeAuthAal2: true, historicalFixtureSetup: true, nativeOnboardingCertified: false, physicalScanningCertified: false, pageErrors: [], steps: [] };
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium' }), context = await browser.newContext({ viewport: { width: 375, height: 960 }, hasTouch: true, serviceWorkers: 'block' });
await context.addCookies([...bag.values()].map(c => ({ name: c.name, value: c.value, url: origin, httpOnly: false, secure: false, sameSite: 'Lax' })));
const page = await context.newPage();
page.on('pageerror', error => proof.pageErrors.push(error.message.slice(0, 500)));
let step = 'open';
try {
    const assurance = await ssr.auth.mfa.getAuthenticatorAssuranceLevel();
    if (assurance.error || assurance.data?.currentLevel !== 'aal2')
        throw new Error('NATIVE_TEST_AAL2_REQUIRED');
    proof.verifiedCurrentLevel = assurance.data.currentLevel;
    await page.goto(`${origin}/fr/client/questionnaires?organizationId=${owner.organizationId}`, { waitUntil: 'networkidle', timeout: 90000 });
    await page.locator('select[name="questionnaireVersionId"]').selectOption(fixture.questionnaireVersion);
    await page.locator('select[name="organizationId"]').selectOption(owner.organizationId);
    await page.getByRole('button', { name: 'Démarrer', exact: true }).click();
    await page.getByRole('link', { name: 'Ouvrir la session', exact: true }).waitFor({ timeout: 20000 });
    await page.getByRole('link', { name: 'Ouvrir la session', exact: true }).click();
    await page.waitForURL(url => url.searchParams.has('session'));
    const sessionId = new URL(page.url()).searchParams.get('session');
    proof.sessionId = sessionId;
    proof.steps.push({ step: 'native_ui_start', passed: true });
    const bool = page.locator('form').filter({ has: page.locator(`input[name="questionVersionId"][value="${fixture.booleanQuestion}"]`) }), detail = page.locator('form').filter({ has: page.locator(`input[name="questionVersionId"][value="${fixture.detailQuestion}"]`) });
    step = 'require';
    await bool.getByRole('radio', { name: 'Oui', exact: true }).check();
    await expect(detail.locator('input[name="answerValue"]')).toHaveAttribute('required', '', { timeout: 20000 });
    proof.steps.push({ step: 'answer_triggers_required_detail', passed: true });
    step = 'missing_required';
    await page.getByRole('button', { name: 'Soumettre', exact: true }).click();
    await expect(page.getByRole('alert').filter({ hasText: 'Certaines réponses obligatoires manquent encore.' })).toBeVisible({ timeout: 15000 });
    proof.steps.push({ step: 'server_refuses_missing_required', passed: true });
    step = 'save_text';
    const free = 'Procédure chantier — خطتي الأصلية';
    await detail.locator('input[name="answerValue"]').fill(free);
    await detail.getByRole('button', { name: 'Enregistrer', exact: true }).click();
    await expect(detail.getByRole('status').filter({ hasText: 'Enregistrée' })).toBeVisible({ timeout: 20000 });
    step = 'offline_queue';
    await context.setOffline(true);
    await detail.locator('input[name="answerValue"]').fill(free + ' — reprise');
    await expect(detail.getByRole('status').filter({ hasText: 'Sauvegarde en attente.' })).toBeVisible();
    proof.steps.push({ step: 'offline_answer_is_queued_without_success_claim', passed: true });
    await context.setOffline(false);
    await expect(detail.getByRole('status').filter({ hasText: 'Sauvegarde en attente.' })).toHaveCount(0, { timeout: 20000 });
    await expect(detail.getByRole('status').filter({ hasText: 'Enregistrée' })).toBeVisible({ timeout: 20000 });
    await page.reload({ waitUntil: 'networkidle' });
    await expect(detail.locator('input[name="answerValue"]')).toHaveValue(free + ' — reprise');
    proof.steps.push({ step: 'reconnect_automatically_saves_queued_answer_then_native_reload', passed: true });
    step = 'arabic';
    await page.goto(`${origin}/ar/client/questionnaires?organizationId=${owner.organizationId}&session=${sessionId}`, { waitUntil: 'networkidle', timeout: 90000 });
    await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
    await expect(detail.locator('input[name="answerValue"]')).toHaveValue(free + ' — reprise');
    proof.steps.push({ step: 'arabic_retains_user_free_text', passed: true });
    await page.screenshot({ path: resolve(dir, 'questionnaire-ar-375.png'), fullPage: true, caret: 'initial' });
    step = 'hide';
    await bool.getByRole('radio', { name: 'لا', exact: true }).check();
    await expect(detail).toHaveCount(0, { timeout: 20000 });
    proof.steps.push({ step: 'changed_answer_hides_irrelevant_detail', passed: true });
    step = 'reload';
    await page.reload({ waitUntil: 'networkidle' });
    await expect(bool.getByRole('radio', { name: 'لا', exact: true })).toBeChecked();
    await expect(detail).toHaveCount(0);
    proof.steps.push({ step: 'native_reload_retains_answer_and_visibility', passed: true });
    step = 'resume';
    await page.goto(`${origin}/fr/client/diagnostics?organizationId=${owner.organizationId}`, { waitUntil: 'networkidle' });
    await expect(page.locator(`a[href*="session=${sessionId}"]`).first()).toBeVisible();
    proof.steps.push({ step: 'diagnostic_hub_resumes_exact_draft', passed: true });
    step = 'filters';
    const complete = page.getByRole('link', { name: 'Diagnostic complet', exact: true });
    await complete.focus();
    await page.keyboard.press('Enter');
    await page.waitForURL(url => url.searchParams.get('kind') === 'complete');
    await expect(page).toHaveURL(new RegExp(`organizationId=${owner.organizationId}`));
    proof.steps.push({ step: 'keyboard_filter_preserves_tenant', passed: true });
    step = 'submit';
    await page.goto(`${origin}/fr/client/questionnaires?organizationId=${owner.organizationId}&session=${sessionId}`, { waitUntil: 'networkidle' });
    await page.getByRole('button', { name: 'Soumettre', exact: true }).click();
    await expect(page.getByText('Cette session a été soumise et reste consultable en lecture seule.', { exact: true })).toBeVisible({ timeout: 20000 });
    await expect(page.getByRole('button', { name: 'Soumettre', exact: true })).toHaveCount(0);
    proof.steps.push({ step: 'submitted_session_is_read_only', passed: true });
    await page.screenshot({ path: resolve(dir, 'questionnaire-submitted-fr-375.png'), fullPage: true, caret: 'initial' });
    if (proof.pageErrors.some(message => /hydration|didn't match/iu.test(message)))
        throw new Error('HYDRATION_REGRESSION');
    proof.status = 'PASSED';
}
catch (e) {
    proof.status = 'FAILED';
    proof.failureStep = step;
    proof.failure = e.message.slice(0, 500);
    process.exitCode = 1;
    await page.screenshot({ path: resolve(dir, 'failure.png'), fullPage: true, caret: 'initial' }).catch(() => { });
    console.log(JSON.stringify({ failureStep: step, message: e.message.slice(0, 200) }));
}
finally {
    await browser.close();
    await writeFile(resolve(dir, 'summary.json'), JSON.stringify(proof, null, 2));
    console.log(JSON.stringify({ status: proof.status, steps: proof.steps.length, evidence: resolve(dir, 'summary.json') }));
}
