import { requireDevelopment, loadOwnState } from './safety.mjs';
import { nativeBrowserActor, preserveBrowserSession, safeError } from './browser-session.mjs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createRequire } from 'node:module';
requireDevelopment();
const state = await loadOwnState();
const fixture = JSON.parse(await readFile(resolve(state.directory, 'catalogue-fixture-provenance.json')));
if (!state.candidate || fixture.scope !== 'HISTORICAL_SQL_TEST_PRECONDITION' || fixture.appTree !== state.candidate.appTree) throw new Error('PINNED_TEST_CATALOGUE_PREREQUISITE_REQUIRED');
const { actor, client, cookies } = await nativeBrowserActor(state, 'provider-owner');
const { chromium, expect } = createRequire(resolve('package.json'))('@playwright/test');
const origin = `http://127.0.0.1:${state.appPort}`, directory = resolve(state.directory, 'questionnaire');
await mkdir(directory, { recursive: true });
const resumeFromStart = process.argv.includes('--resume-questionnaire');
let previous;
if(resumeFromStart){previous=JSON.parse(await readFile(resolve(directory,'summary.json')));if(previous.appTree!==state.candidate.appTree||previous.status!=='FAILED'||!['services','start'].includes(previous.failureStage)||previous.steps.length!==3||previous.sessionId)throw new Error('EXACT_PRE_START_QUESTIONNAIRE_CHECKPOINT_REQUIRED');}
const proof = { scope: 'NATIVE_PROVIDER_UI_SERVICES_CAPACITY_AND_CONDITIONAL_QUESTIONNAIRE', candidate: state.candidate.commit, appTree: state.candidate.appTree, status: 'RUNNING', steps: [], pageErrors: [], fixtureScope: fixture.scope };
if(resumeFromStart)proof.steps.push(...previous.steps);
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium' });
const context = await browser.newContext({ viewport: { width: 375, height: 960 }, hasTouch: true, serviceWorkers: 'block' });
await context.addCookies(cookies);
const page = await context.newPage();
page.on('pageerror', error => proof.pageErrors.push(safeError(error.message)));
let stage = 'services';
try {
 if(!resumeFromStart){
  await page.goto(`${origin}/fr/sous-traitant/qualification?organizationId=${actor.organizationId}`, { waitUntil: 'networkidle', timeout: 90000 });
  for (const serviceId of [fixture.ids.serviceA, fixture.ids.serviceB]) {
    const form = page.locator('form').filter({ has: page.locator('select[name="serviceId"]') }).filter({ hasNot: page.locator('select[name="capacityStatus"]') });
    await form.locator('select[name="serviceId"]').selectOption(serviceId);
    await form.getByRole('button').last().focus();
    await page.keyboard.press('Enter');
    await expect.poll(async () => { const r = await client.from('provider_services').select('id').eq('provider_organization_id', actor.organizationId).eq('service_id', serviceId); return r.error ? -1 : r.data.length; }, { timeout: 20000 }).toBe(1);
    await page.reload({ waitUntil: 'networkidle' });
  }
  proof.steps.push({ step: 'two_native_service_requests_persist_in_same_provider', passed: true });
  const capacity = page.locator('form').filter({ has: page.locator('select[name="capacityStatus"]') });
  await capacity.locator('select[name="serviceId"]').selectOption('');
  await capacity.locator('select[name="capacityStatus"]').selectOption('AVAILABLE');
  await capacity.locator('[name="availableUnits"]').fill('7');
  await capacity.locator('[name="leadTimeDays"]').fill('3');
  await capacity.locator('[name="reason"]').fill('TEST uniquement — capacité globale déclarée pour cette recette.');
  await capacity.getByRole('button').last().tap();
  await expect.poll(async () => { const r = await client.from('provider_capacity_versions').select('available_units,lead_time_days').eq('provider_organization_id', actor.organizationId).is('service_id', null).order('version_number', { ascending: false }).limit(1); return r.data?.[0]; }, { timeout: 20000 }).toEqual({ available_units: 7, lead_time_days: 3 });
  proof.steps.push({ step: 'touch_declared_global_capacity_persists_without_qualification_approval', passed: true });
  const regions = page.locator('form').filter({ has: page.locator('input[name="regionCodes"]') });
  await regions.locator('input[name="regionCodes"][value="CASABLANCA_SETTAT"]').check();
  await regions.locator('[name="reason"]').fill('TEST uniquement — zone déclarée pour le dossier de recette.');
  await regions.getByRole('button').last().tap();
  await expect.poll(async () => { const r = await client.from('provider_match_profiles').select('region_codes').eq('provider_organization_id', actor.organizationId).single(); return r.error ? [] : r.data.region_codes; }, { timeout: 20000 }).toContain('CASABLANCA_SETTAT');
  const modes = page.locator('form').filter({ has: page.locator('input[name="modes"]') });
  await modes.locator('[name="modes"][value="ONSITE"]').check();
  await modes.locator('[name="reason"]').fill('TEST uniquement — prestation sur site déclarée.');
  await modes.getByRole('button').last().tap();
  await expect.poll(async () => { const r = await client.from('provider_intervention_mode_versions').select('modes').eq('provider_organization_id', actor.organizationId).order('version_number', { ascending: false }).limit(1); return r.data?.[0]?.modes ?? []; }, { timeout: 20000 }).toContain('ONSITE');
  const scope = page.locator('form').filter({ has: page.locator('input[name="radiusKm"]') });
  await scope.locator('[name="radiusKm"]').fill('80');
  await scope.locator('[name="missionSizeSummary"]').fill('TEST uniquement — petits chantiers et interventions planifiées.');
  await scope.locator('[name="reason"]').fill('TEST uniquement — déclaration indépendante de la qualification.');
  await scope.getByRole('button').last().focus(); await page.keyboard.press('Enter');
  await expect.poll(async () => { const r = await client.from('provider_work_scope_versions').select('intervention_radius_km').eq('provider_organization_id', actor.organizationId).order('version_number', { ascending: false }).limit(1); return r.data?.[0]?.intervention_radius_km; }, { timeout: 20000 }).toBe(80);
  proof.steps.push({ step: 'native_regions_modes_radius_and_mission_size_declarations', passed: true });
 }
  stage = 'start';
  await page.goto(`${origin}/fr/sous-traitant/questionnaires?organizationId=${actor.organizationId}`, { waitUntil: 'networkidle', timeout: 90000 });
  await page.locator('select[name="questionnaireVersionId"]').selectOption(fixture.ids.questionnaireVersion);
  await page.locator('form').filter({has:page.locator('select[name="questionnaireVersionId"]')}).locator('select[name="organizationId"]').selectOption(actor.organizationId);
  await page.getByRole('button', { name: 'Démarrer', exact: true }).focus();
  await page.keyboard.press('Enter');
  await page.getByRole('link', { name: 'Ouvrir la session', exact: true }).click();
  await page.waitForURL(url => url.searchParams.has('session'));
  const sessionId = new URL(page.url()).searchParams.get('session');
  proof.sessionId = sessionId;
  const persisted = await client.from('questionnaire_sessions').select('organization_id,audience,is_simulation,status').eq('id', sessionId).single();
  if (persisted.error || persisted.data.organization_id !== actor.organizationId || persisted.data.audience !== 'PROVIDER' || persisted.data.is_simulation !== false) throw new Error('REAL_SCOPED_PROVIDER_QUESTIONNAIRE_REQUIRED');
  proof.steps.push({ step: 'published_provider_questionnaire_started_from_real_ui', passed: true });
  const boolean = page.locator('form').filter({ has: page.locator(`input[name="questionVersionId"][value="${fixture.ids.booleanQuestion}"]`) });
  const detail = page.locator('form').filter({ has: page.locator(`input[name="questionVersionId"][value="${fixture.ids.detailQuestion}"]`) });
  stage = 'required';
  await boolean.getByRole('radio', { name: 'Oui', exact: true }).check();
  await expect(detail.locator('input[name="answerValue"]')).toHaveAttribute('required', '', { timeout: 20000 });
  await page.getByRole('button', { name: 'Soumettre', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Certaines réponses obligatoires manquent encore.' })).toBeVisible({ timeout: 15000 });
  const notSubmitted = await client.from('questionnaire_sessions').select('status').eq('id', sessionId).single();
  if (notSubmitted.error || notSubmitted.data.status === 'SUBMITTED') throw new Error('SERVER_MISSING_REQUIRED_MUST_NOT_SUBMIT');
  proof.steps.push({ step: 'conditional_required_rule_and_independent_server_refusal', passed: true });
  stage = 'offline';
  const freeText = 'Procédure TEST de recette — خطتي الأصلية';
  await detail.locator('input[name="answerValue"]').fill(freeText);
  await detail.getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await expect(detail.getByRole('status').filter({ hasText: 'Enregistrée' })).toBeVisible({ timeout: 20000 });
  await context.setOffline(true);
  await detail.locator('input[name="answerValue"]').fill(freeText + ' — reprise');
  await expect(detail.getByRole('status').filter({ hasText: 'Sauvegarde en attente.' })).toBeVisible();
  await context.setOffline(false);
  await expect(detail.getByRole('status').filter({ hasText: 'Sauvegarde en attente.' })).toHaveCount(0, { timeout: 20000 });
  await expect(detail.getByRole('status').filter({ hasText: 'Enregistrée' })).toBeVisible({ timeout: 20000 });
  await page.reload({ waitUntil: 'networkidle' });
  await expect(detail.locator('input[name="answerValue"]')).toHaveValue(freeText + ' — reprise');
  proof.steps.push({ step: 'offline_queue_reconnect_and_persisted_native_reload', passed: true });
  stage = 'arabic';
  await page.goto(`${origin}/ar/sous-traitant/questionnaires?organizationId=${actor.organizationId}&session=${sessionId}`, { waitUntil: 'networkidle' });
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await expect(detail.locator('input[name="answerValue"]')).toHaveValue(freeText + ' — reprise');
  await boolean.getByRole('radio', { name: 'لا', exact: true }).check();
  await expect(detail).toHaveCount(0, { timeout: 20000 });
  await page.reload({ waitUntil: 'networkidle' });
  await expect(boolean.getByRole('radio', { name: 'لا', exact: true })).toBeChecked();
  proof.steps.push({ step: 'arabic_original_free_text_and_persisted_conditional_visibility', passed: true });
  await page.screenshot({ path: resolve(directory, 'conditional-ar-375.png'), fullPage: true });
  stage = 'resume';
  await page.goto(`${origin}/fr/sous-traitant/questionnaires?organizationId=${actor.organizationId}`, { waitUntil: 'networkidle' });
  const resume = page.locator(`a[href*="session=${sessionId}"]`).first();
  await resume.focus();
  await page.keyboard.press('Enter');
  await page.waitForURL(url => url.searchParams.get('session') === sessionId);
  await boolean.getByRole('radio', { name: 'Oui', exact: true }).check();
  await expect(detail.locator('input[name="answerValue"]')).toHaveValue(freeText + ' — reprise', { timeout: 20000 });
  proof.steps.push({ step: 'keyboard_resume_exact_draft_and_restore_answer', passed: true });
  stage = 'submit';
  await page.getByRole('button', { name: 'Soumettre', exact: true }).click();
  await expect(page.getByText('Cette session a été soumise et reste consultable en lecture seule.', { exact: true })).toBeVisible({ timeout: 20000 });
  await expect(page.getByRole('button', { name: 'Soumettre', exact: true })).toHaveCount(0);
  const submitted = await client.from('questionnaire_sessions').select('status,is_simulation,audience').eq('id', sessionId).single();
  if (submitted.error || submitted.data.status !== 'SUBMITTED' || submitted.data.is_simulation || submitted.data.audience !== 'PROVIDER') throw new Error('NATIVE_PROVIDER_SUBMISSION_NOT_PERSISTED');
  proof.steps.push({ step: 'native_provider_submission_is_persisted_and_read_only', passed: true });
  await page.screenshot({ path: resolve(directory, 'submitted-fr-375.png'), fullPage: true });
  if (proof.pageErrors.length) throw new Error('NATIVE_PROVIDER_QUESTIONNAIRE_BROWSER_ERRORS');
  proof.status = 'PASSED';
} catch (error) {
  proof.status = 'FAILED'; proof.failureStage = stage; proof.failure = safeError(error.message); process.exitCode = 1;
  await page.screenshot({ path: resolve(directory, 'failure.png'), fullPage: true }).catch(() => {});
} finally {
  await preserveBrowserSession(state, 'provider-owner', context).catch(error => { if (proof.status === 'PASSED') { proof.status = 'FAILED'; proof.failure = safeError(error.message); process.exitCode = 1; } });
  await browser.close();
  await writeFile(resolve(directory, 'summary.json'), JSON.stringify(proof, null, 2));
  console.log(JSON.stringify({ status: proof.status, steps: proof.steps.length, failureStage: proof.failureStage, failure: proof.failure }));
}
