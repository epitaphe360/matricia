import {readFileSync} from "node:fs";
import {spawnSync} from "node:child_process";
import {createHash} from "node:crypto";
import {resolve,dirname} from "node:path";
import {fileURLToPath} from "node:url";
const database=process.argv[2],fixturePath=process.argv[3],plan=process.argv[4];
if(!database||!/^matricia_delivery_[a-z0-9_]+$/u.test(database)||!fixturePath||!fixturePath.endsWith(".sql")||plan&&!["PREMIUM","GOLD","PLATINUM"].includes(plan))throw new Error("Explicit local clone and reviewed Client0256 fixture required.");
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const original=readFileSync(fixturePath,"utf8");
if(!original.includes("create temporary table p256")||!original.includes("CUSTOMER_BOX_CONFIGURED"))throw new Error("BOX_FIXTURE_SOURCE_CHANGED");
let sql=original.replace(/select\s+\*\s*from\s+finish\(\);\s*rollback;\s*$/iu,"");
if(sql===original)throw new Error("BOX_FIXTURE_BOUNDARY_CHANGED");
if(plan)sql=sql.replaceAll("'PREMIUM'","'"+plan+"'");
sql+="\n"+readFileSync(resolve(root,"supabase/fixtures/benefit_box_binding_contract_checks.sql"),"utf8");
process.stdout.write("Input fixture sha256 "+createHash("sha256").update(original).digest("hex")+(plan?" ; synthetic catalogue code "+plan:"")+"\n");
const r=spawnSync("docker",["exec","-i","supabase_db_Matricia","psql","-X","-U","postgres","-d",database,"-v","ON_ERROR_STOP=1"],{input:sql,encoding:"utf8",timeout:120000,maxBuffer:4*1024*1024});
const output=(r.stdout??"")+"\n"+(r.stderr??"");
for(const line of output.split("\n"))if(/^\s*(ok \d|not ok|1\.\.|ROLLBACK)|ERROR:|Failed test|Looks like you failed/u.test(line))process.stdout.write(line.trim()+"\n");
if(r.error||r.status!==0||/not ok|ERROR:|Looks like you failed/u.test(output)||!output.includes("ROLLBACK"))throw new Error("BENEFIT_BOX_BINDING_FAILED");
